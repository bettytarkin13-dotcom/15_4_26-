    ID INTEGER PRIMARY KEY,
	EMAIL TEXT NOT NULL UNIQUE,
	STUDENT_NAME TEXT NOT NULL,
	GRADE REAL CHECK(GRADE BETWEEN 0 AND 100),
	STATUS TEXT DEFAULT 'PENDING'
);

